| GAS-syntax port of common68k.s, for the m68k-amigaos-gcc feasibility
| investigation -- not used by the real vbcc/vasm build. Byte-compared
| against the vasm original; do not edit this file without re-running
| that comparison.
|
| _Q_memcpy is omitted entirely: it's fully commented out in the real
| source (every line prefixed with ";", not just IFD'd out) and isn't
| in the real file's XDEF list either -- confirmed via the real file's
| own header comment ("using compiler version of memcpy, see
| common.h"). Confirmed via the real file's assembled symbol table
| (m68k-amigaos-nm) that only _ShortSwap/_LongSwap/_FloatSwap(__r) are
| actually present -- nothing to byte-compare _Q_memcpy against since
| vasm itself never emits it.
|
| rsreset/rs.l/rs.w/rs.s stack-offset constants (this file's structure-
| offset mechanism -- same purpose as setso/so.l used in the other
| files in this series, different directive name, same arithmetic)
| folded to final numeric values, same as every other file here:
| _ShortSwap's .data = 6 (rsreset=0, then an unnamed rs.l 1 for the
| 4-byte return address -> 4, then an unnamed rs.w 1 -> 6, then
| .data itself); _LongSwap and _FloatSwap's .data = 4 (rsreset=0, one
| unnamed rs.l 1 for the return address -> 4, then .data itself --
| no extra padding slot, unlike _ShortSwap).
|
| No local dot-labels at all in this file (every real function is
| straight-line code, no internal branches) -- nothing to rename.
|
| Unlike mathlib68k.s, no GAS-specific suffix quirks needed here:
| probed "move (N,sp),d0" (bare, no size suffix), "ror #8,d0" (bare),
| "swap d0" (inherently unambiguous, no size variants exist), and
| "fmove.s d0,fp0" (data register as the source EA for an FPU op,
| explicit .s already present in vasm's own source) against the real
| assembler before use -- all accepted as-is, no changes needed.

	.text

	.balign	4
	.globl	_ShortSwap
_ShortSwap:
	move	(6,sp),d0
	ror	#8,d0
	rts

	.balign	4
	.globl	_LongSwap
_LongSwap:
	move.l	(4,sp),d0
	ror	#8,d0
	swap	d0
	ror	#8,d0
	rts

	.balign	4
	.globl	_FloatSwap
	.globl	_FloatSwap__r
_FloatSwap:
_FloatSwap__r:
	move.l	(4,sp),d0
	ror	#8,d0
	swap	d0
	ror	#8,d0
	fmove.s	d0,fp0
	rts
