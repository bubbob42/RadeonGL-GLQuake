| surgeon: mousebuttons are handled in c
|
| Input interrupt routine for mouse control
|
| used for M68k as well as for PowerPC
|
| modified by Matt Hey <matthey7@gmail.com>
|
| GAS-syntax port of in_amigamouse68k.s, for the m68k-amigaos-gcc
| feasibility investigation -- not used by the real vbcc/vasm build.
| Byte-compared against the vasm original; do not edit this file
| without re-running that comparison.
|
| InputIntDat field offsets (must match struct InputIntDat in
| in_amigamouse.c) -- copied numerically since GAS has no STRUCTURE
| directive:
|   iid_MouseX          = 0  (WORD)
|   iid_MouseY          = 2  (WORD)
|   iid_LeftButtonDown  = 4  (UBYTE)
|   iid_LeftButtonUp    = 5  (UBYTE)
|   iid_RightButtonDown = 6  (UBYTE)
|   iid_RightButtonUp   = 7  (UBYTE)
|   iid_MidButtonDown   = 8  (UBYTE)
|   iid_MidButtonUp     = 9  (UBYTE)
|
| InputEvent field offsets and ie_Class/ie_Code constants, verified
| against the real D:\NDK_39\Include\include_i\devices\inputevent.i:
|   ie_NextEvent = 0   (APTR)
|   ie_Class     = 4   (UBYTE)
|   ie_Code      = 6   (UWORD, low byte at +1 since big-endian)
|   ie_X         = 10  (WORD; ie_Y follows immediately at 12, so a
|                        single move.l at offset 10 copies both)
|   IECLASS_RAWMOUSE = 0x02
|   IECODE_LBUTTON   = 0x68  (also uses IECODE_UP_PREFIX, 0x80)
|   IECODE_RBUTTON   = 0x69
|   IECODE_MBUTTON   = 0x6a

	.text

	.globl	_InputIntCode
	.globl	InputIntCode
_InputIntCode:
InputIntCode:
	move.l	a0,-(sp)
Lloop:
	cmpi.b	#0x02,(4,a0)
	bne.b	Lnext
	move.b	(7,a0),d0
	smi	d1			| if IECODE_UP_PREFIX
	and.w	#0x7f,d0		| clear IECODE_UP_PREFIX
	cmp.w	#0x68,d0
	beq.b	Llmb
	cmp.w	#0x69,d0
	beq.b	Lrmb
	cmp.w	#0x6a,d0
	beq.b	Lmmb
Lmove:
	move.l	(10,a0),(0,a1)	| ie_X,ie_Y -> iid_MouseX,iid_MouseY
Lnext:
	move.l	(0,a0),a0
	tst.l	a0
	bne.b	Lloop
	move.l	(sp)+,d0
	rts

Llmb:
	move.b	d1,(5,a1)
	not.l	d1
	move.b	d1,(4,a1)
	bra.b	Lmove
Lrmb:
	move.b	d1,(7,a1)
	not.l	d1
	move.b	d1,(6,a1)
	bra.b	Lmove
Lmmb:
	move.b	d1,(9,a1)
	not.l	d1
	move.b	d1,(8,a1)
	bra.b	Lmove
