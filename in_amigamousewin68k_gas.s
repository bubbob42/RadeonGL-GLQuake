|   IECLASS_RAWKEY = 0x01

	.text

	.globl	_InputIntCodeWin
	.globl	InputIntCodeWin
_InputIntCodeWin:
InputIntCodeWin:
	move.l	a0,-(sp)
Lloop:
	cmp.b	#0x02,(4,a0)
	bne.b	Lnext
	move.b	(7,a0),d0
	smi	d1			| if IECODE_UP_PREFIX
	and.w	#0x7f,d0		| clear IECODE_UP_PREFIX
	cmp.w	#0x68,d0
	beq.b	Llmb
	cmp.w	#0x69,d0
	beq.b	Lrmb
	cmp.w	#0x6a,d0
	beq.b	Lmmb
Lmove:
| 2026-11-06: ADD each event's movement. Copying kept only the last event's:
| with several RAWMOUSE events a frame (a mouse reports faster than GLQuake
| draws) the others were lost, and turning speed depended on the frame rate.
	move.w	(10,a0),d0
	add.w	d0,(0,a1)		| iid_MouseX += ie_X
	move.w	(12,a0),d0
	add.w	d0,(2,a1)		| iid_MouseY += ie_Y
Lnext:
	move.l	(0,a0),a0
	tst.l	a0
	bne.b	Lloop
	move.l	(sp)+,d0
	rts

Llmb:
|	move.b  d1,(iid_LeftButtonUp,a1)
|	not.l   d1
|	move.b  d1,(iid_LeftButtonDown,a1)
	and.w	#0x80,d1
	move.b	#0x01,(4,a0)
	or.w	#0x63,d1
	move.w	d1,(6,a0)
	bra.b	Lmove
Lrmb:
	move.b	d1,(7,a1)
	not.l	d1
	move.b	d1,(6,a1)
	bra.b	Lmove
Lmmb:
	move.b	d1,(9,a1)
	not.l	d1
	move.b	d1,(8,a1)
	bra.b	Lmove
