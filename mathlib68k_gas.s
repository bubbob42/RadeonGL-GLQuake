	jsr	_sin
	movem.l	d0-d1,-(sp)
	fmove.d	(sp)+,fp2		| sr
	jsr	_cos
	movem.l	d0-d1,-(sp)
	fmove.d	(sp)+,fp5		| cr
	addq.l	#8,sp
	.endif
	.endif

| forward[0] = cp*cy;
| forward[1] = cp*sy;
| forward[2] = -sp;
