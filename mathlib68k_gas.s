	fmul.x	fp7,fp0
	move.l	(84,sp),a0
	fmove.s	fp0,(a0)+
	fmove.s	fp6,-(sp)
	fmul.x	fp4,fp6
	fneg.x	fp3,fp1
	fmove.s	fp6,(a0)+
	fmove.s	fp1,(a0)+

| right[0] = (-1*sr*sp*cy+-1*cr*-sy);
| right[1] = (-1*sr*sp*sy+-1*cr*cy);
