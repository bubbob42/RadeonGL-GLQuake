| GAS-syntax port of mathlib68k.s, for the m68k-amigaos-gcc feasibility
| investigation -- not used by the real vbcc/vasm build. Byte-compared
| against the vasm original; do not edit this file without re-running
| that comparison.
|
| SCOPE: the real file is ~1050 lines, but DEADCODE and M881 are both
| undefined everywhere in this project (confirmed via grep across the
| whole glquake tree -- no -D flag in any build script, no SET in any
| included header). Per vasm's own IFD semantics, every function
| wrapped in "IFD DEADCODE ... ENDC" is never assembled into the real
| object -- confirmed empirically by assembling the real mathlib68k.s
| and listing its symbol table (m68k-amigaos-nm): only the 8 functions
| below are present. Those dead functions (_BoxOnPlaneSide,
| __DotProduct, __VectorSubtract, __VectorAdd, __VectorCopy,
| _VectorInverse, _Q_log2, _R_ConcatRotations, _R_ConcatTransforms,
| _FloorDivMod, _GreatestCommonDivisor, _Invert24To16) are omitted
| here entirely, not translated -- there is nothing to byte-compare
| against since vasm itself never emits them.
|
| setso/so.l/so.s stack-offset constants are replaced by their
| computed final numeric values throughout (GAS has no structure-
| offset-counter directive) -- each so.l/so.s slot is 4 bytes, so.d
| would be 8 (unused in the real, non-dead portion of this file).
| Local dot-labels renamed to L-prefixed names per this series'
| established convention; the two originally both named ".1" (in
| _VectorCompare and _VectorNormalize -- vasm scopes dot-locals per
| preceding global label, so they don't collide there) are
| disambiguated here as L1/L2 since GAS labels are file-scope.
|
| _AngleVectors' three IFD M881/ELSE/ENDC blocks (PITCH/YAW/ROLL) are
| kept as real .ifdef M881/.else/.endif blocks here, per explicit user
| request, even though M881 is undefined project-wide today -- this
| makes the file ready to test M881 later (see
| [[project_minigl_v3d_m881_fsincos_perf_question]]) under GCC too,
| not just vbcc. BUT: this GAS port has no fsincos/fsin/fcos/facos/
| fatan/ftan/fetox/flogn mnemonics at all (these are 68881/68882-
| coprocessor-specific transcendental instructions, dropped from the
| 68040/68060's integrated FPU and apparently never given assembler
| support in this GCC-oriented binutils port, presumably because
| compiler-generated code calls libm instead of emitting them
| directly) -- confirmed by grepping the assembler binary's own
| strings (absent entirely, not just under some flag combination) and
| by trying every plausible operand syntax (comma/colon-separated,
| various -m flags) against the real binary, all giving "Unknown
| operator" (the "mnemonic not recognized" error, not a "bad operand"
| error). This is a real toolchain gap, not a syntax question -- so
| the M881 branch below is written as raw ".word" bytes instead of the
| fsincos mnemonic, copied VERBATIM from vasm's own real "-DM881"
| assembly of this exact file (not hand-derived from the FPU
| instruction-format tables -- too easy to get the source/dual-
| destination register fields wrong by hand, and there's no need to
| when vasm's own real output is sitting right there). Byte-verified
| against that real vasm -DM881 output, same as every other
| instruction in this file is verified against vasm's default
| (M881-undefined) output.
|
| Two floating immediates are vasm "#$<hex>" raw IEEE-754 bit-pattern
| literals, not decimal constants -- GAS's float-immediate syntax has
| no equivalent hex-bit-pattern reinterpretation, so each was converted
| to its exact value via Python's struct module (guaranteed round-trip
| decimal repr, confirmed by re-encoding back to the identical hex
| bytes before use): $4066c16c16c16c17 (double) = 182.04444444444445,
| $3c8efa35 (single) = 0.01745329238474369. Byte-verified equal to
| vasm's output after assembly (see below), not just assumed correct.
|
| _CrossProduct's "add.w #12,a0" is written here as vasm's own
| optimizer output "lea (12,a0),a0" directly (vasm's -showopt flagged
| this substitution on the real file) -- ADDA/SUBA-immediate never
| affects the CCR in the first place, so this is vasm's normal,
| always-on, unconditional optimization for this pattern, not a
| context-dependent judgement call. Written to match bytes directly
| rather than relying on GAS independently choosing the same encoding.
|
| Two GAS-specific FPU syntax requirements, found by probing (not
| documented anywhere obvious, and different from vasm's own rules):
| 1. A register-to-register FPU op with NO memory operand (fmove,
|    fmul, fadd, fsub, fneg, fsqrt, fdiv) needs an explicit ".x" size
|    suffix in GAS -- vasm accepts these bare. Functionally identical
|    either way (register operands are always extended-precision
|    internally regardless of suffix; the size field only means
|    anything for a memory EA), and confirmed byte-identical to vasm's
|    bare-mnemonic output below -- so ".x" is added throughout purely
|    to satisfy GAS's parser, not because it changes anything.
| 2. fbne/fbeq (floating conditional branch) reject BOTH ".w" and
|    ".b" suffixes in GAS ("Unknown operator" either way) -- only the
|    bare mnemonic is accepted, unlike this series' other (integer)
|    branches which needed an explicit size to match vasm. Written
|    bare here; byte-verified below to confirm GAS's own default
|    choice for these four still lands on the same 16-bit-displacement
|    encoding vasm's -showopt reported (FBcc has no 8-bit form at all,
|    so vasm's ".w" here was never a size vasm "chose" over a smaller
|    option -- it's the only option).
|
| REAL BUG FIX (2026-08-09, GCC-vs-vbcc rendering investigation): the
| .else (M881-undefined, what actually ships) branches of _AngleVectors'
| three sin/cos pairs originally read the result straight out of fp0
| after each "jsr _sin"/"jsr _cos", matching vasm/vbcc's own real
| library convention (vbcc's non-intrinsic _sin/_cos genuinely return
| via fp0). Confirmed via direct disassembly that libm881.a's REAL
| _sin/_cos (the library this project's GCC glquake build links
| against) do NOT follow that convention: `fmoved 4(sp),fp0` loads the
| argument, `fsinx fp0,fp1`/`fcosx fp0,fp1` computes the result INTO
| fp1 (leaving fp0 UNCHANGED -- still the raw input angle, not garbage,
| which is why this wasn't obviously catastrophic-looking), then
| `fmoved fp1,-(sp)` + two `move.l (sp)+,dN` return the real result via
| d0:d1 (d0=high word, d1=low word of the double) -- the real clib2/GCC
| ABI for a double-returning function, same convention already found
| for libm881.a's math_cos.o/math_sin.o in an earlier investigation
| (project_minigl_v3d_m881_fsincos_perf_question), just never checked
| against THIS hand-written call site before now. Net effect under the
| old code, on real GCC+libm881 builds: every sin/cos pair returned the
| SAME raw input angle for both "sin" and "cos" (fp0 unchanged by
| either call), not their actual trig values -- AngleVectors' forward/
| right/up output was real garbage on every call, on every frame,
| whenever this ships as the actual GAS translation. Fixed by pulling
| the real result out of d0:d1 into an FP register via a stack-neutral
| push/pop (two move.l pushes + one fmove.d pop, net stack effect zero)
| instead of trusting fp0 -- keeps the real hardware sin/cos call
| (faster than falling back to portable C mathlib.c, which was the
| user's explicit preference over a C fallback), fixes the ABI mismatch
| directly at the call site. This makes this file NO LONGER a byte-for-
| byte match with vasm's own output for these three blocks specifically
| (intentional, real divergence -- vasm/vbcc's target library doesn't
| have this bug, so vasm's own output never needed this fix) -- do not
| "re-sync to vasm" for _AngleVectors specifically if re-verifying this
| file later. The M881-defined branches (raw fsincos, see below) are
| entirely unaffected -- that's a single hardware instruction computing
| both results directly into two FP registers, no external call, no ABI
| dependency at all.
|
| A 4th accepted-difference category, narrower/more context-dependent
| than the other three (established in earlier files in this series)
| -- NOT a general rule, only safe for this specific case:
| 4. "jsr _sin"/"jsr _cos" assemble to "bsr.l" (PC-relative,
|    RELRELOC32) in GAS, where vasm's real output uses "jsr" (absolute,
|    a different relocation type) for the identical call. Tried three
|    different GAS syntax forms ("jsr sym", "jsr sym:l", "jsr (sym)")
|    -- all three produced the identical bsr.l/RELRELOC32 encoding, so
|    this GAS port appears to have no way to force absolute JSR
|    addressing to an external, assembly-time-undefined symbol at all.
|    This would be a real concern given this investigation's own
|    earlier finding that GNU ld mishandles RELRELOC32 relocations
|    targeting symbols *exported from vasm-produced hunk objects* --
|    but _sin/_cos are plain libm/clib2 functions (confirmed: grepped
|    the whole glquake tree, the only match is gl_mirror.i's prototype
|    declaration, no project file defines them), not vasm-exported
|    symbols, so that specific bug doesn't apply here. This
|    investigation's own earlier control test already confirmed ld
|    correctly resolves relative relocations into GCC-compiled targets
|    -- libm/clib2 is exactly that case. Accepted on that basis, not
|    just assumed safe.

