	fmul.s	(a2)+,fp2
	.ifdef	M881
	.word	0xf200,0x0935		| fsincos fp2,fp5:fp2 (see header)
	.else
	.ifdef	MGLV3D_TEST_DIRECT_TRIG
	| REAL BUG, caught by real-hardware "stuck at console, never scrolls
	| up" testing (2026-08-09): the first version of this block used
	| "fsinx fp2,fp2" (self-referencing) then "fcos.d (sp),fp5" + a
	| trailing "addq.l #8,sp" copied from the library-call branch below,
	| which assumes something was pushed to (sp) earlier in THIS branch.
	| Nothing is -- PITCH/YAW's own DIRECT_TRIG branches correctly never
	| touch the stack either, matching M881's own no-stack pattern -- so
	| under this build variant, (sp) at this point is actually pointing
	| at this function's OWN saved a2/fp2-fp7 prologue data, and the
	| addq.l then permanently shifted the stack by 8 bytes for the rest
	| of the function, corrupting the later restores and ultimately the
	| return address itself. Fixed by removing the stack dependency
	| entirely (matching M881) and using fp1 -- confirmed genuinely free/
	| unused until later in this function -- instead of self-referencing
	| fp2, so fp2 still holds the real angle for the fcosx read below.
	fsinx	fp2,fp1			| sr -> fp1 (temp, fp2 still holds the angle)
	fcosx	fp2,fp5			| cr (register source only, no memory/stack at all)
	fmovex	fp1,fp2			| now copy sr into fp2, matching where the rest
					| of this function (and the M881/library-call
					| branches) expect to find it
	.else
