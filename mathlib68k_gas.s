	fmove.x	fp4,fp0
	fmul.x	fp3,fp1
	move.l	(92,sp),a0
	fmul.x	fp5,fp0
	fmove.x	fp1,fp6
	fmul.x	fp7,fp6
	fsub.x	fp6,fp0
	fmove.s	fp0,(a0)+
	fmul.x	fp4,fp1
	fneg.x	fp5,fp0
	fmul.x	fp7,fp0
	fsub.x	fp1,fp0
	fmove.s	fp0,(a0)+
	fneg.x	fp2,fp1
	fmul.s	(sp),fp1
	fmove.s	fp1,(a0)+

