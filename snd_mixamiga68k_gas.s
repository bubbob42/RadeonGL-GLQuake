|
|  Sound mixing routines for Amiga 68k
|  Written by Frank Wille <frank@phoenix.owl.de>
|
| This implementation of S_TransferPaintBuffer() handles the following
| two formats:
|
| 1. 8-bits STEREO for Amiga native Paula sound-chip.
|    DMA buffer layout (8 bits signed samples):
|    <-- shm.samples bytes left ch. --><-- shm.samples bytes right ch. -->
|
| 2. 16-bits STEREO for AHI.
|    DMA buffer layout (16 bits signed big-endian samples):
|    <-- shm.samples * (<16bits left ch.>|<16 bits right ch.>) -->
|
| GAS-syntax port of snd_mixamiga68k.s, for the m68k-amigaos-gcc
| feasibility investigation -- not used by the real vbcc/vasm build.
| Byte-compared against the vasm original; do not edit this file
| without re-running that comparison.
|
| dma_t struct offsets verified against the real, pre-existing,
| already-hand-verified quakedef68k.i (do not regenerate that file):
|   dma_samples     = 16
|   dma_samplebits  = 28
|   dma_buffer      = 36
|
| endtim replaces the original's setso/so.l stack-offset computation
| (4 bytes return address + 8 registers * 4 bytes saved by the
| movem.l below = 36) -- GAS has no structure-offset-counter directive,
| so the already-computed numeric result is used directly instead.
| _shm, _paintbuffer, _paintedtime, _volume are external (xref in the
| original; GAS treats any referenced-but-undefined symbol as
| external automatically, no declaration needed).
|
| Every muls.l Dm,Dl (32-bit single-register result) in this file
| byte-matches vasm except for the extension word's low 3 bits (the
| Dh field). Confirmed against NXP's official M68000 PRM MULS page:
| bits 14-12 = Dl (the real, executed destination register -- matches
| the source operand identically in both assemblers, every occurrence);
| bits 2-0 = Dh, and the manual states outright "If size is one,
| specifies the data register into which the high-order 32 bits of the
| product are loaded... Otherwise, this field is unused." vasm fills
| the unused field by duplicating Dl; GAS fills it with 0. Confirmed
| benign -- same accepted-difference category as the AND/CMP-immediate
| dual encoding and the cnop/.balign fill-byte difference below.

endtim = 36

	.text

	.globl	_S_TransferPaintBuffer
	.balign	4
_S_TransferPaintBuffer:
	movem.l	d2-d7/a2-a3,-(sp)

	fmove.s	#0f256.0,fp0
	move.l	_shm,a1			| a1 shm (struct dma_t)
	fmul.s	_volume+16,fp0		| volume.value * 256
	lea	_paintbuffer,a0		| a0 paintbuffer (int left,int right)
	move.l	_paintedtime,d6
	move.l	(endtim,sp),d2
	sub.l	d6,d2			| d2 count
	beq	Lexit
	move.l	(36,a1),a3	| a3 dma buffer start address
	move.l	(16,a1),d0
	moveq	#8,d1
	fmove.l	fp0,d3			| d3 snd_vol
	cmp.l	(28,a1),d1
	beq.b	Lpaula8bit	| vasm auto-shrinks this unsized branch to .b;
				| GAS defaults an unsized forward branch here to
				| .w instead, so the size is forced explicitly to
				| match vasm's real, verified choice.

| 16-bit AHI transfer
	lea	(a3,d0.l*2),a2		| a2 dma buffer end address
	lsr.l	#1,d0
	subq.l	#1,d0
	and.l	d0,d6
	move.l	#0x7fff,d5
	move.l	d5,d4			| d4 max val
	not.l	d5			| d5 min val
	lea	(a3,d6.l*4),a1		| a1 out
	move.l	a2,d6
	sub.l	a3,d6			| d6 buffer size
Lloop16:
	move.l	(a0)+,d0
	muls.l	d3,d0
	move.l	(a0)+,d1
	asr.l	#8,d0
	muls.l	d3,d1
	cmp.l	d4,d0
	ble.b	L161
	move.l	d4,d0
	bra.b	L162
L161:	cmp.l	d5,d0
	bge.b	L162
	move.l	d5,d0
L162:	asr.l	#8,d1
	swap	d0
	cmp.l	d4,d1
	ble.b	L163
	move.l	d4,d1
	bra.b	L164
L163:	cmp.l	d5,d1
	bge.b	L164
	move.l	d5,d1
L164:	move.w	d1,d0			| d0 leftCh16.W | rightCh16.W
	move.l	d0,(a1)+
	cmp.l	a2,a1
	blo.b	L165
	sub.l	d6,a1
L165:	subq.l	#1,d2
	bne.b	Lloop16
	movem.l	(sp)+,d2-d7/a2-a3
	rts

Lpaula8bit:
	lsr.l	#1,d0			| dma_samples / 2
	moveq	#0x7f,d4		| d4 max val
	move.l	d0,d1
	subq.l	#1,d1
	moveq	#-0x80,d5		| d5 min val
	and.l	d1,d6
	lea	(a3,d0.l),a2		| a2 dma buffer end address
	lea	(a3,d6.l),a1		| a1 out
	move.l	a2,d6
	sub.l	a3,d6			| d6 buffer size
	move.l	d0,a3			| a3 stereo buffer offset
Lloop8:
	move.l	a1,d0
	and.w	#3,d0			| 32-bit aligned output?
	beq.b	Lloop8aligned
Lloop8unaligned:
	move.l	(a0)+,d0
	muls.l	d3,d0
	move.l	(a0)+,d1
	swap	d0
	muls.l	d3,d1
	cmp.w	d4,d0
	ble.b	L1
	move.l	d4,d0
	bra.b	L2
L1:	cmp.w	d5,d0
	bge.b	L2
	move.l	d5,d0
L2:	swap	d1
	move.b	d0,(a1)+		| left channel
	cmp.w	d4,d1
	ble.b	L3
	move.l	d4,d1
	bra.b	L4
L3:	cmp.w	d5,d1
	bge.b	L4
	move.l	d5,d1
L4:	move.b	d1,(-1,a1,a3.l)		| right channel
	cmp.l	a2,a1
	blo.b	L5
	sub.l	d6,a1
L5:	subq.l	#1,d2
	bne.b	Lloop8
	bra	Lexit
Lloop8aligned:
	moveq	#4,d0
	cmp.l	d0,d2
	blo.b	Lloop8unaligned
	move.l	(a0)+,d0
	muls.l	d3,d0
	swap	d0
	cmp.w	d4,d0
	ble.b	L10
	move.w	d4,d0
	bra.b	L11
L10:	cmp.w	d5,d0
	bge.b	L11
	move.w	d5,d0
L11:	move.l	(a0)+,d1
	lsl.w	#8,d0			| left ch. byte 0
	muls.l	d3,d1
	swap	d1
	cmp.w	d4,d1
	ble.b	L12
	move.w	d4,d1
	bra.b	L13
L12:	cmp.w	d5,d1
	bge.b	L13
	move.w	d5,d1
L13:	move.l	(a0)+,d7
	lsl.w	#8,d1			| right ch. byte 0
	muls.l	d3,d7
	swap	d7
	cmp.w	d4,d7
	ble.b	L14
	move.l	d4,d7
	bra.b	L15
L14:	cmp.w	d5,d7
	bge.b	L15
	move.l	d5,d7
L15:	move.b	d7,d0			| left ch. byte 1
	move.l	(a0)+,d7
	swap	d0
	muls.l	d3,d7
	swap	d7
	cmp.w	d4,d7
	ble.b	L16
	move.l	d4,d7
	bra.b	L17
L16:	cmp.w	d5,d7
	bge.b	L17
	move.l	d5,d7
L17:	move.b	d7,d1			| right ch. byte 1
	move.l	(a0)+,d7
	swap	d1
	muls.l	d3,d7
	swap	d7
	cmp.w	d4,d7
	ble.b	L18
	move.l	d4,d7
	bra.b	L19
L18:	cmp.w	d5,d7
	bge.b	L19
	move.l	d5,d7
L19:	lsl.l	#8,d7
	move.w	d7,d0			| left ch. byte 2
	move.l	(a0)+,d7
	muls.l	d3,d7
	swap	d7
	cmp.w	d4,d7
	ble.b	L20
	move.l	d4,d7
	bra.b	L21
L20:	cmp.w	d5,d7
	bge.b	L21
	move.l	d5,d7
L21:	lsl.l	#8,d7
	move.w	d7,d1			| right ch. byte 2
	move.l	(a0)+,d7
	muls.l	d3,d7
	swap	d7
	cmp.w	d4,d7
	ble.b	L22
	move.l	d4,d7
	bra.b	L23
L22:	cmp.w	d5,d7
	bge.b	L23
	move.l	d5,d7
L23:	move.b	d7,d0			| left ch. byte 3
	move.l	(a0)+,d7
	muls.l	d3,d7
	swap	d7
	move.l	d0,(a1)+		| write left channel
	cmp.w	d4,d7
	ble.b	L24
	move.l	d4,d7
	bra.b	L25
L24:	cmp.w	d5,d7
	bge.b	L25
	move.l	d5,d7
L25:	move.b	d7,d1			| right ch. byte 3
	move.l	d1,(-4,a1,a3.l)		| write right channel
	cmp.l	a2,a1
	blo.b	L30
	sub.l	d6,a1
L30:	subq.l	#4,d2
	bne	Lloop8aligned

Lexit:	movem.l	(sp)+,d2-d7/a2-a3
	rts
